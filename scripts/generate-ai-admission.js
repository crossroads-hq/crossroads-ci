// Editorial generator only. Admission/reviewer jobs never execute this script.
// CI runs --check through deterministic tests, without reviewer credentials.
// Keep the legacy entry byte-for-byte unchanged; its reviewer remains the owner.
const { readFileSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');
const PIN = 'e627853734c095ad2a35d95d47b6089107310ae4';
function replaceOnce(source, from, to) {
  if (!source.includes(from) || source.indexOf(from) !== source.lastIndexOf(from)) {
    throw new Error('AI reviewer owner workflow changed; review generator anchors');
  }
  return source.replace(from, to);
}
function render(source) {
  const guard = source.match(/^    if: >-\n((?:      .*\n)+)/m)?.[1];
  if (!guard) throw new Error('AI reviewer owner workflow guard changed');
  let result = replaceOnce(source, source.slice(0, source.indexOf('\nname: AI review\n')),
    '# GENERATED by scripts/generate-ai-admission.js from _ai-review.yml.\n' +
    '# Edit the owner reviewer, regenerate, then review both diffs.\n' +
    '# HQ-085 Story 7: dormant opt-in only; no caller or enrollment enabled.\n' +
    '# Fixed workload AI / capability fast; root on light, actual heavy on fast.\n' +
    '# Advisory: never include these jobs in PR Validation.\n');
  result = replaceOnce(result, '\nname: AI review\n', '\nname: AI review admission\n');
  result = replaceOnce(result, '    inputs:\n', `    inputs:
      admission-enabled:
        description: Select the dormant AI admission path. This does not enroll a repository or activate the pilot.
        type: boolean
        required: false
        default: false
`);
  const runnerInput = result.match(/      runner-labels:\n[\s\S]*?(?=      job-timeout-minutes:)/)?.[0];
  if (!runnerInput) throw new Error('AI reviewer owner workflow runner input changed');
  result = replaceOnce(result, runnerInput, '');
  result = replaceOnce(result, 'jobs:\n', `jobs:
  admission-ai:
    name: Admission AI
    if: >-
      inputs.admission-enabled &&
${guard}    permissions:
      contents: read
      actions: read
      checks: read
      pull-requests: read
    runs-on: [self-hosted, Linux, X64, light]
    timeout-minutes: 2
    steps:
      - name: Verify AI launch without waiting for heavy
        uses: crossroads-hq/crossroads-ci/actions/admission-root@${PIN} # HQ-085 Story 6 draft #132

`);
  result = replaceOnce(result, '  review:\n    name: AI review\n', '  review:\n    name: AI review\n    needs: admission-ai\n');
  // Only the heavy guard gets the dependency: root must never wait for heavy.
  result = replaceOnce(result, '    if: >-\n' + guard,
    "    if: >-\n      inputs.admission-enabled &&\n      needs.admission-ai.result == 'success' &&\n" + guard);
  result = replaceOnce(result, '      actions: read\n      # The action exchanges',
    '      actions: read\n      # Admission adds Checks reads only. Existing reviewer write grants remain\n' +
    '      # job-scoped; they cannot be reduced per step. See enrollment blocker\n' +
    '      # in docs/ci-admission-ai.md. No scheduler credential enters this job.\n' +
    '      checks: read\n      # The action exchanges');
  result = replaceOnce(result, '    runs-on: ${{ fromJSON(inputs.runner-labels) }}', '    runs-on: [self-hosted, Linux, X64, fast]');
  result = replaceOnce(result, '    steps:\n      # First, and pure arithmetic', `    steps:
      # Every actual attempt verifies before ANY checkout, install or reviewer.
      # No cached root output, caller-selected identity or fail-open fallback.
      - name: Verify fresh AI job before checkout
        uses: crossroads-hq/crossroads-ci/actions/admission-checkout@${PIN} # HQ-085 Story 6 draft #132

      # First, and pure arithmetic`);
  return result;
}
module.exports = { render };
if (require.main === module) {
  const root = join(__dirname, '..');
  const target = join(root, '.github/workflows/_ai-review-admission.yml');
  const expected = render(readFileSync(join(root, '.github/workflows/_ai-review.yml'), 'utf8'));
  if (process.argv[2] === '--check') {
    if (readFileSync(target, 'utf8') !== expected) {
      console.error('AI admission workflow drifted; regenerate and review it'); process.exitCode = 1;
    }
  } else if (process.argv.length === 2) writeFileSync(target, expected);
  else { console.error('Usage: node scripts/generate-ai-admission.js [--check]'); process.exitCode = 1; }
}
